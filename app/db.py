# ---------------------------------------------------------------- Postgres 适配

def _translate(sql: str) -> str:
    """把 SQLite 写法的 SQL 转成 Postgres 可执行形式。"""
    s = sql
    # datetime('now', '-30 days')  →  (NOW() + ('-30 days')::interval)
    # 注意用 +：绑定参数本身带负号，NOW() - interval '-30 days' 会变成往后推。
    s = re.sub(r"datetime\(\s*'now'\s*,\s*\?\s*\)", "(NOW() + (?)::interval)", s, flags=re.I)
    was_or_ignore = bool(re.search(r"INSERT\s+OR\s+IGNORE\s+INTO", s, re.I))
    s = re.sub(r"INSERT\s+OR\s+IGNORE\s+INTO", "INSERT INTO", s, flags=re.I)
    if was_or_ignore and "on conflict" not in s.lower():
        s = s.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    return s.replace("?", "%s")


class PgRow(dict):
    """同时支持 row["col"] 和 row[0]，对齐 sqlite3.Row 的取法。"""

    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return dict.__getitem__(self, key)


class _PgCursor:
    def __init__(self, cur):
        self._cur = cur

    def execute(self, sql, params=None):
        stmt = _translate(sql)
        if params is None:
            self._cur.execute(stmt)
        else:
            self._cur.execute(stmt, params)
        return self

    def executemany(self, sql, seq):
        self._cur.executemany(_translate(sql), list(seq))
        return self

    def _wrap(self, row):
        if row is None:
            return None
        if isinstance(row, dict):
            return PgRow(row)
        return PgRow({str(i): v for i, v in enumerate(row)})

    def fetchone(self):
        return self._wrap(self._cur.fetchone())

    def fetchall(self):
        return [self._wrap(r) for r in self._cur.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())


class _PgConn:
    def __init__(self, raw):
        self._raw = raw

    def execute(self, sql, params=None):
        cur = self._raw.cursor()
        stmt = _translate(sql)
        if params is None:
            cur.execute(stmt)
        else:
            cur.execute(stmt, params)
        return _PgCursor(cur)

    def executemany(self, sql, seq):
        cur = self._raw.cursor()
        cur.executemany(_translate(sql), list(seq))
        return _PgCursor(cur)

    def cursor(self):
        return _PgCursor(self._raw.cursor())

    def commit(self):
        self._raw.commit()

    def rollback(self):
        self._raw.rollback()

    def close(self):
        self._raw.close()


def get_conn():
    """取连接：有 DATABASE_URL 走 Postgres，否则本地 SQLite 文件。"""
    if USE_POSTGRES:
        from psycopg import connect
        from psycopg.rows import dict_row
        return _PgConn(connect(DATABASE_URL, row_factory=dict_row, autocommit=False))
    conn = sqlite3.connect(DB_PATH, timeout=10)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    conn.execute("PRAGMA journal_mode = WAL")
    conn.execute("PRAGMA busy_timeout = 10000")
    return conn


def init_db():
    conn = get_conn()
    if USE_POSTGRES:
        for stmt in _PG_SCHEMA.split(";"):
            if stmt.strip():
                conn.execute(stmt)
        conn.commit()
    else:
        conn.executescript(_SQLITE_SCHEMA)
        conn.commit()
    conn.close()


